import { PrismaClient } from "@prisma/client";
import fs from "fs";
const prisma = new PrismaClient();
(async () => {
  const SLUGS: string[] = [
    "geometry-trigonometry", "statistics-probability", "further-mathematics",
    "visual-arts", "drama-theatre", "design-technology",
    "physical-education", "health-education", "life-orientation",
  ];
  const topics = await prisma.topic.findMany({
    where: { slug: { in: SLUGS } },
    select: { id: true, slug: true },
  });
  const found: Record<string, string> = {};
  for (const t of topics) {
    found[t.slug as string] = t.id;
  }
  const missing = SLUGS.filter((s) => !(s in found));
  if (missing.length) throw new Error("topics not found: " + missing.join(", "));

  const entries = Object.entries(found);
  let total = 0;
  for (const [slug, topicId] of entries) {
    const res = await prisma.question.updateMany({
      where: { topicId, sourceExam: "WAEC" },
      data: { sourceExam: "original-exam-style" },
    });
    console.log(slug + ": " + res.count + " relabelled");
    total += res.count;
  }

  const ids: string[] = [];
  for (const [slug, topicId] of entries) {
    const qs = await prisma.question.findMany({ where: { topicId, sourceExam: "original-exam-style" }, select: { id: true } });
    for (const q of qs) ids.push(q.id);
  }
  const file = JSON.parse(fs.readFileSync("content/questions/relabel-sourceExam.json", "utf8"));
  file.ids = ids;
  file.count = ids.length;
  file.note = "REGENERATED by topic slug (was stale short slugs: trig/stats/further/visual-arts/drama-theatre/design-technology/physical-education/health-education/life-orientation). " + ids.length + " ids across " + entries.length + " topics.";
  fs.writeFileSync("content/questions/relabel-sourceExam.json", JSON.stringify(file, null, 2) + "\n");
  console.log("TOTAL relabelled: " + total);
  console.log("rewrote relabel-sourceExam.json: " + ids.length + " ids");
  await prisma.$disconnect();
})();
